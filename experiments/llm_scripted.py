"""Modelos de linguagem simulados, usados APENAS nas experiências.

As experiências isolam as camadas determinísticas do sistema (recolha de dados, regras, avaliação, coordenação).
As perguntas qualitativas, normalmente respondidas pelo modelo, recebem respostas fixas e otimistas; as citações
usadas como prova são copiadas dos textos reais das fontes, por isso passam na verificação de citações do sistema.
As variantes que "alucinam" violam as regras de propósito, para testar as salvaguardas.
"""
import re

_QUOTE = (re.compile(r"=== FRASES SOBRE PREÇOS \(RELATÓRIO ANUAL\) ===\n\[.*?\]\n1\. (.+)"),
          re.compile(r"=== PREÇOS PRATICADOS \(RELATÓRIO ANUAL\) ===\n\[.*?\]\n- (.+)"),
          re.compile(r"(Relatório anual de 2025: [^\n]+?\.)"))

def _quote(msg):
    for rx in _QUOTE:
        m = rx.search(msg)
        if m: return m.group(1).strip()
    return None

class ScriptedLLM:
    """Respostas otimistas que cumprem as regras: todos os testes qualitativos dizem "sim"; a prova é uma citação real das fontes."""
    backend = "simulado"; modelo = "simulado (otimista)"
    def __init__(self): self.calls = {}
    def _count(self, a): self.calls[a] = self.calls.get(a, 0) + 1
    def quote(self, msg): return _quote(msg)
    def json(self, agente, sistema, msg, tentativas=3):
        self._count(agente); q = self.quote(msg)
        if agente.startswith("analista"):
            fr = {k: {"resposta": "sim", "porque": "simulado"} for k in ("f1", "f2", "f3", "f4")}
            return {"t1": {"resposta": "sim", "porque": "simulado"}, "circulo": {"resposta": "sim", "wrigley": "sim", "porque": "simulado"},
                    "modelo": "M1", "modelo_porque": "simulado", "c2": {"resposta": "sim", "porque": "simulado"},
                    "c3": {"resposta": "sim", "evidencia": q, "porque": "simulado"}, "franquia": fr}
        if agente.startswith("critico"): return {"objecoes": []}
        if agente == "coletor":
            return {"mapeamentos": {"Turnover (net)": "receita", "Group net profit": "resultado_liquido",
                                    "Cash generated by operations": "fco"}}
        return {}

class FabricatedQuoteLLM(ScriptedLLM):
    """Teste de salvaguarda: afirma poder de preço com uma citação que NÃO existe nas fontes."""
    FAKE = "Em 2025 subimos os preços 12% em todos os produtos sem qualquer perda de volume."
    def quote(self, msg): return self.FAKE

class FabricatedNumberLLM(ScriptedLLM):
    """Teste de salvaguarda: na parte qualitativa do Avaliador, o modelo justifica a franquia com um número que não está nos dados."""
    def json(self, agente, sistema, msg, tentativas=3):
        r = super().json(agente, sistema, msg, tentativas)
        if agente == "analista":
            r["franquia"]["f2"]["porque"] = "A empresa tem uma quota de mercado de 83,7% e uma margem de 731,9%, por isso não tem substituto."
        return r

class AlwaysObjectingCritic(ScriptedLLM):
    """Teste de salvaguarda: o Crítico (Munger) levanta uma objeção grave sempre que é chamado."""
    def json(self, agente, sistema, msg, tentativas=3):
        if agente.startswith("critico"):
            self._count(agente)
            return {"objecoes": [{"gravidade": "grave", "campo": "franquia", "descricao": "a afirmação de franquia não está fundamentada"}]}
        return super().json(agente, sistema, msg, tentativas)
